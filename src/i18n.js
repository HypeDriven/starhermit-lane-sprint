for (const id of Object.keys(OVERRIDES)) {
	STRINGS[id] = Object.assign({}, STRINGS['en-US'], OVERRIDES[id]);
}

let current = 'en-US';

export function availableLocales() { return LOCALES.slice(); }

export function negotiateLocale(preferred, navigatorLanguages) {
	const known = new Set(LOCALES.map(l => l.id));
	if (preferred && known.has(preferred)) return preferred;
	const list = Array.isArray(navigatorLanguages) ? navigatorLanguages : [];
	for (const tag of list) {
		if (known.has(tag)) return tag;
		const base = String(tag).split('-')[0].toLowerCase();
		if (base === 'es') return /^es-es$/i.test(tag) ? 'es-ES' : 'es-419';
		if (base === 'fr') return /ca/i.test(tag) ? 'fr-CA' : 'fr-FR';
		if (base === 'pt') return 'pt-BR';
		if (base === 'de') return 'de-DE';
		if (base === 'it') return 'it-IT';
		if (base === 'en') return /gb|uk/i.test(tag) ? 'en-GB' : 'en-US';
	}
	return 'en-US';
}

export function setLocale(id) {
	current = STRINGS[id] ? id : 'en-US';
	if (typeof document !== 'undefined' && document.documentElement) {
		document.documentElement.lang = current;
	}
	return current;
}

export function getLocale() { return current; }

export function t(key, params) {
	const table = STRINGS[current] || STRINGS['en-US'];
	let s = table[key];
	if (s == null) s = STRINGS['en-US'][key];
	if (s == null) return key;
	if (params) {
		for (const k of Object.keys(params)) s = s.split('{' + k + '}').join(String(params[k]));
	}
	return s;
}

/** Test hook: every locale must cover every en-US key. */
export function missingKeys() {
	const base = Object.keys(STRINGS['en-US']);
	const out = {};
	for (const l of LOCALES) {
		const table = STRINGS[l.id] || {};
		const missing = base.filter(k => typeof table[k] !== 'string' || !table[k].length);
		if (missing.length) out[l.id] = missing;
	}
	return out;
}
