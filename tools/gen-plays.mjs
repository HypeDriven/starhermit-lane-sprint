// Writes the engine play scripts that drive whole stages through the real UI
// (tests/native/*.play): a bot plays the stage with the browser build's rules
// (src/rules.js, src/content.js — the reference solver's cautious lane policy
// plus a boost on long clear stretches) and its commands become timed key
// lines. Timing on the engine (measured, 1.18.0): after the `until` that sees
// the run's HUD, the first key line acts on tick 2; every line takes one
// frame (one fixed step) and `frames N` takes N + 1, and a command lands on
// the tick its key line acts on (session.sendCommand), so the script replays
// the bot's run exactly.
//   node tools/gen-plays.mjs
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createInitialState, applyAction, step, isTerminal, scoreBreakdown, LANE_COUNT, CAR_LENGTH } from '../src/rules.js';
import { getStage } from '../src/content.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const KEYS = { lane_left: 'ArrowLeft', lane_right: 'KeyD', boost: 'Space' };

/** The bot's run: [{ tick, action }] and the final state. `boost`: use boosts on clear stretches. */
export function plan(stage, { boost = true, start = 2 } = {}) {
  const state = createInitialState(stage);
  const cmds = [];
  const clearance = (lane) => {
    let best = Infinity;
    for (const car of state.traffic) {
      if (car.lane !== lane) continue;
      const gap = car.z - state.position;
      if (gap < -CAR_LENGTH) continue;
      if (gap < best) best = gap;
    }
    return best;
  };
  let lastCmd = -10;
  while (!isTerminal(state) && state.tick < 60000) {
    // Commands at least two ticks apart (a key line each), none before the script's first key line.
    if (state.tick >= start && state.tick - lastCmd >= 2) {
      let act = null;
      if (clearance(state.lane) < 55) {
        let target = state.lane, bestGap = clearance(state.lane);
        for (let lane = 0; lane < LANE_COUNT; lane++) { const g = clearance(lane); if (g > bestGap) { bestGap = g; target = lane; } }
        if (target !== state.lane) {
          const next = target < state.lane ? state.lane - 1 : state.lane + 1;
          if (clearance(next) > CAR_LENGTH * 2.5) act = target < state.lane ? 'lane_left' : 'lane_right';
        }
      } else if (boost && clearance(state.lane) > 150 && !state.boostActive && state.elapsed >= state.boostReadyAt) act = 'boost';
      if (act && applyAction(state, act)) { cmds.push({ tick: state.tick, action: act }); lastCmd = state.tick; }
    }
    step(state);
  }
  return { cmds, state };
}

/** Key lines for the commands, from the first key line's tick (2). */
function lines(cmds, start = 2) {
  const out = [];
  let c = start;
  for (const { tick, action } of cmds) {
    if (tick > c) out.push(`frames ${tick - c - 1}`);
    out.push(`key ${KEYS[action]} 1`);
    c = tick + 1;
  }
  return out;
}

function write(name, header, body) {
  writeFileSync(join(root, 'tests', 'native', name), header.map((l) => `# ${l}`).join('\n') + '\n' + body.join('\n') + '\n');
  console.log(`wrote tests/native/${name}`);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) main();

function main() {
// Stage 1 to the finish (generated by tools/gen-plays.mjs), then Next stage, a crash on stage 2 by driving straight, Retry, Quit.
const s1 = plan(getStage(1));
if (!s1.state.finished) throw new Error('the bot does not finish stage 1');
const total1 = scoreBreakdown(s1.state).total;
write('stage-1-finish.play', [
  'Stage 1 driven to the finish by the bot of tools/gen-plays.mjs (generated: do not edit), its total',
  `checked on the results (${total1}); then Next stage, Pause, Restart, a crash on stage 2 by holding the`,
  'middle lane, and Quit to title.',
], [
  'until 300 Lane Sprint', 'frames 30', 'click =Play stage 1', 'until 60 Boost ready', ...lines(s1.cmds),
  'until 600 Stage complete', 'frames 20', `expect ${total1}`, 'save stage-1-results',
  'click =Next stage', 'until 60 Stage 2', 'frames 30', 'key Escape 1', 'until 60 Resume', 'frames 10', 'click =Restart',
  'until 60 Boost ready', 'until 3000 Crashed', 'frames 20', 'save stage-2-crash',
  'click =Retry stage', 'until 60 Boost ready', 'frames 10', 'key KeyR 1', 'until 60 Boost ready', 'frames 10',
  'key Escape 1', 'until 60 Resume', 'frames 10', 'click =Quit to title', 'until 60 Play stage 2', 'frames 10',
]);
}
